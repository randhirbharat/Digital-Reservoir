"""Self-contained HTML engineering report for an analysis run (printable to PDF from the browser)."""
from __future__ import annotations

import html
import json

from .models import AnalysisRun, Dataset, DatasetVersion, User

DISCLAIMER = ("This report is decision-support information generated by the Digital Reservoir Engineering Lab. It is not a structural-safety "
              "certification, a statutory dam-safety assessment or a substitute for qualified engineering judgement, inspection and project-specific review.")


def _svg_lines(series: list[tuple[str, dict, str]], height: int = 220) -> str:
    pts_all = [v for _, s, _ in series for v in (s.get("y") or []) if v is not None]
    if not pts_all:
        return ""
    lo, hi = min(pts_all), max(pts_all)
    hi = hi if hi > lo else lo + 1
    W, H, L = 760, height, 50
    out = [f'<svg viewBox="0 0 {W} {H}" width="100%" role="img" aria-label="Chart" style="border:1px solid #d9dbd2;border-radius:8px;background:#fff">']
    for frac in (0, 0.5, 1):
        y = 10 + frac * (H - 30)
        out.append(f'<line x1="{L}" x2="{W - 10}" y1="{y:.1f}" y2="{y:.1f}" stroke="#e5e7e1"/><text x="4" y="{y + 4:.1f}" font-size="10" fill="#4c5c62">{hi - frac * (hi - lo):.3g}</text>')
    for name, s, color in series:
        ys = s.get("y") or []
        n = max(1, len(ys) - 1)
        d = []
        pen = False
        for i, v in enumerate(ys):
            if v is None:
                pen = False
                continue
            x = L + i * (W - L - 10) / n
            y = 10 + (hi - v) / (hi - lo) * (H - 30)
            d.append(f"{'L' if pen else 'M'}{x:.1f},{y:.1f}")
            pen = True
        out.append(f'<path d="{"".join(d)}" fill="none" stroke="{color}" stroke-width="1.6"/>')
    legend = " ".join(f'<span style="color:{c}">■</span> {html.escape(n)}' for n, _, c in series)
    out.append("</svg>")
    return "".join(out) + f'<div style="font-size:12px;color:#4c5c62">{legend}</div>'


def _table(rows: list[dict], cols: list[str] | None = None) -> str:
    if not rows:
        return ""
    cols = cols or list(rows[0].keys())
    def fmt(v):
        if isinstance(v, float):
            return f"{v:.4g}"
        if isinstance(v, (dict, list)):
            return html.escape(json.dumps(v)[:120])
        return html.escape(str(v)) if v is not None else "—"
    head = "".join(f"<th>{html.escape(c)}</th>" for c in cols)
    body = "".join("<tr>" + "".join(f"<td>{fmt(r.get(c))}</td>" for c in cols) + "</tr>" for r in rows)
    return f'<div style="overflow-x:auto"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


def render(run: AnalysisRun, user: User, version: DatasetVersion | None, dataset: Dataset | None) -> str:
    r = run.result or {}
    parts = [f"<h1>{html.escape(run.title)}</h1>",
             f'<p class="meta">Run {run.id} · {run.created_at.isoformat()} · engine v{html.escape(run.engine_version)} · prepared for {html.escape(user.full_name)}</p>']
    if dataset and version:
        parts.append(f'<p class="meta">Dataset: {html.escape(dataset.name)} (version {version.version}: {html.escape(version.label)}; SHA-256 {version.sha256[:16]}…; provenance: <strong>{html.escape(dataset.provenance)}</strong>)</p>')
    parts.append(f"<h2>Method</h2><p>{html.escape(str(r.get('method', run.kind)))}</p>")
    if r.get("formula"):
        parts.append(f'<pre>{html.escape(r["formula"])}</pre>')
    if r.get("definitions"):
        parts.append(_table([{"symbol": k, "definition": v} for k, v in r["definitions"].items() if v]))
    if r.get("assumptions"):
        parts.append("<h2>Assumptions</h2><ul>" + "".join(f"<li>{html.escape(a)}</li>" for a in r["assumptions"]) + "</ul>")
    parts.append(f"<h2>Parameters</h2><pre>{html.escape(json.dumps(run.params, indent=2, default=str))}</pre>")
    if r.get("periods"):
        parts.append("<h2>Calibration and validation periods</h2>" + _table([{"period": k, "value": v} for k, v in r["periods"].items()]))
    if isinstance(r.get("metrics"), dict):
        rows = [{"period": k, **v} for k, v in r["metrics"].items() if isinstance(v, dict)]
        parts.append("<h2>Performance</h2>" + _table(rows, ["period", "n", "MAE", "RMSE", "R2", "bias", "max_abs_error"]))
    if r.get("coefficients"):
        parts.append("<h2>Parameters estimated</h2>" + _table(r["coefficients"]))
    if r.get("ranking"):
        parts.append("<h2>Model ranking (validation RMSE)</h2>" + _table(r["ranking"]))
    if r.get("indicators") and run.kind == "dhi":
        parts.append(f"<h2>Index</h2><p>DHI = {r.get('index'):.3f} — {html.escape(str(r.get('classification')))}</p>" + _table(r["indicators"], ["name", "current_value", "normalised", "weight", "contribution"]))
    ser = r.get("series") if isinstance(r.get("series"), dict) else None
    if ser and "observed" in ser and "predicted" in ser:
        parts.append("<h2>Observed and predicted</h2>" + _svg_lines([("Observed", ser["observed"], "#9b8461"), ("Predicted", ser["predicted"], "#183c45")]))
        if "residual" in ser:
            parts.append(_svg_lines([("Residual", ser["residual"], "#2c6b61")], 160))
    if r.get("warnings"):
        parts.append("<h2>Warnings</h2><ul>" + "".join(f"<li>{html.escape(w)}</li>" for w in r["warnings"]) + "</ul>")
    for key in ("limitations", "note", "interpretation"):
        if r.get(key):
            val = r[key]
            parts.append(f"<h2>{key.title()}</h2>" + ("<ul>" + "".join(f"<li>{html.escape(x)}</li>" for x in val) + "</ul>" if isinstance(val, list) else f"<p>{html.escape(str(val))}</p>"))
    parts.append(f'<h2>Engineering interpretation</h2><p class="box">To be completed by the responsible engineer. Automated outputs above are not an engineering determination.</p><p class="disc">{DISCLAIMER}</p>')
    css = ("body{font:14px/1.55 Inter,Segoe UI,Arial,sans-serif;color:#10232d;max-width:900px;margin:32px auto;padding:0 16px}h1{font-family:Manrope,Inter,sans-serif;font-size:26px}"
           "h2{font-size:17px;margin-top:28px;border-bottom:1px solid #d9dbd2;padding-bottom:4px}.meta{color:#4c5c62;font-size:12px}pre{background:#f5f4ef;padding:10px;border-radius:8px;overflow-x:auto;font-size:12px}"
           "table{border-collapse:collapse;font-size:12px;width:100%}th,td{border-bottom:1px solid #e5e7e1;padding:5px 8px;text-align:left;white-space:nowrap}th{background:#f1f3f0}"
           ".box{border:1px dashed #9b8461;padding:12px;border-radius:8px}.disc{font-size:12px;color:#4c5c62;border-top:1px solid #d9dbd2;padding-top:10px}@media print{body{margin:0}}")
    return f'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex"><title>{html.escape(run.title)}</title><style>{css}</style></head><body>{"".join(parts)}</body></html>'
