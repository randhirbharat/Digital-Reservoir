"""Generate the SYNTHETIC example datasets used by Digital Reservoir demonstrations.

These files do not describe any real structure. Every file carries a `# SYNTHETIC` header line
explaining its origin, and the generating equations are documented below so results are traceable.

Run:  python datasets/generate_synthetic.py
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

import numpy as np

OUT = Path(__file__).parent
RNG = np.random.default_rng(20261104)


def gravity_dam_daily(days: int = 3 * 365) -> None:
    """Daily records for an illustrative gravity dam (2023-01-01 .. ).

    level H(t)  = 605 + 6 sin(2π(d-60)/365.25) + 1.5 sin(2π d/730) + noise
    h           = (H_max - H)/(H_max - H_min) with H_max=614, H_min=596
    displacement = 2.0 - 6.0 h + 2.5 h² - 1.2 cos(2π(d-20)/365.25) + 0.35 ln(1 + t_years) + ε (σ=0.12 mm)
    PZ03 head   = 36.0 + 0.62 (H - 600) lagged 5 days + ε
    seepage     = 9.0 + 0.45 (H - 600) + 0.6 cos(2π d/365.25) + ε
    """
    rows = []
    levels = []
    for d in range(days):
        H = 605 + 6 * math.sin(2 * math.pi * (d - 60) / 365.25) + 1.5 * math.sin(2 * math.pi * d / 730) + RNG.normal(0, 0.08)
        levels.append(H)
    for d in range(days):
        H = levels[d]
        h = (614 - H) / (614 - 596)
        t = d / 365.25
        temp = 18 + 9 * math.sin(2 * math.pi * (d - 110) / 365.25) + RNG.normal(0, 1.6)
        disp = 2.0 - 6.0 * h + 2.5 * h * h - 1.2 * math.cos(2 * math.pi * (d - 20) / 365.25) + 0.35 * math.log(1 + t) + RNG.normal(0, 0.12)
        pz = 36.0 + 0.62 * (levels[max(0, d - 5)] - 600) + RNG.normal(0, 0.05)
        seep = 9.0 + 0.45 * (H - 600) + 0.6 * math.cos(2 * math.pi * d / 365.25) + RNG.normal(0, 0.15)
        date = np.datetime64("2023-01-01") + np.timedelta64(d, "D")
        rows.append([f"{date}T00:00:00Z", f"{disp:.4f}", f"{H:.3f}", f"{temp:.2f}", f"{pz:.3f}", f"{seep:.3f}"])
    # Inject documented data-quality issues for teaching: 6 missing values, 3 duplicate rows, 2 spikes.
    for i in (100, 101, 102, 400, 401, 700):
        rows[i][1] = ""
    rows[250][1] = f"{float(rows[250][1]) + 4.5:.4f}"
    rows[820][4] = f"{float(rows[820][4]) + 3.0:.3f}"
    rows.insert(301, list(rows[300]))
    rows.insert(602, list(rows[601]))
    rows.insert(903, list(rows[902]))
    with open(OUT / "demo_gravity_dam_daily.csv", "w", newline="") as f:
        f.write("# SYNTHETIC example data generated by datasets/generate_synthetic.py - not a real structure\n")
        w = csv.writer(f)
        w.writerow(["timestamp", "PL01_disp_mm", "reservoir_level_m", "air_temp_C", "PZ03_head_m", "V02_seepage_Ls"])
        w.writerows(rows)


def ambient_vibration(fs: float = 100.0, seconds: int = 120) -> None:
    """Two-mode response (3.2 Hz, ζ=2 %; 7.9 Hz, ζ=3 %) to white-noise excitation plus sensor noise."""
    n = int(fs * seconds)
    dt = 1 / fs
    out = np.zeros((n, 2))
    for k, (f0, z, amp) in enumerate([(3.2, 0.02, 1.0), (7.9, 0.03, 0.5)]):
        w = 2 * math.pi * f0
        x = v = 0.0
        exc = RNG.normal(0, 1, n)
        resp = np.zeros(n)
        for i in range(n):  # semi-implicit Euler integration of x'' + 2ζω x' + ω² x = f
            a = exc[i] * 50 - 2 * z * w * v - w * w * x
            v += a * dt
            x += v * dt
            resp[i] = -(2 * z * w * v + w * w * x)
        out[:, k] = resp * amp
    ch1 = out[:, 0] + out[:, 1] + RNG.normal(0, 0.5, n)
    ch2 = 0.6 * out[:, 0] - 0.9 * out[:, 1] + RNG.normal(0, 0.5, n)
    with open(OUT / "demo_ambient_vibration_100Hz.csv", "w", newline="") as f:
        f.write("# SYNTHETIC two-mode ambient vibration (3.2 Hz, 7.9 Hz) at 100 Hz - not a real structure\n")
        w = csv.writer(f)
        w.writerow(["time_s", "ACC1_mg", "ACC2_mg"])
        for i in range(n):
            w.writerow([f"{i * dt:.2f}", f"{ch1[i]:.4f}", f"{ch2[i]:.4f}"])


def ida_results() -> None:
    """Synthetic multiple-stripe results: 11 PGA levels × 20 records; capacity ~ lognormal(θ=0.55 g, β=0.40)."""
    caps = np.exp(math.log(0.55) + 0.40 * RNG.normal(0, 1, 20))
    with open(OUT / "demo_fragility_stripes.csv", "w", newline="") as f:
        f.write("# SYNTHETIC multiple-stripe analysis results (true θ=0.55 g, β=0.40) - not a real structure\n")
        w = csv.writer(f)
        w.writerow(["record_id", "pga_g", "edp_crack_length_ratio", "exceeds_ds2"])
        for pga in np.round(np.linspace(0.1, 1.1, 11), 2):
            for r, c in enumerate(caps):
                edp = 0.4 * (pga / c) ** 1.1 * math.exp(RNG.normal(0, 0.1))
                w.writerow([f"GM{r + 1:02d}", f"{pga:.2f}", f"{edp:.4f}", int(pga >= c)])


if __name__ == "__main__":
    gravity_dam_daily()
    ambient_vibration()
    ida_results()
    print("written:", *sorted(p.name for p in OUT.glob("demo_*.csv")))
